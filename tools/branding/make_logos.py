#!/usr/bin/env python3
"""Cut the four "Aaron's Drink Butler" logos out of the 2x2 options sheet and
turn them into splash-screen assets.

    python make_logos.py [--sheet assets/branding/logo_options.webp]

Writes:
  assets/branding/logo_<n>.png               preview of each splash logo
  firmware/components/ui/assets/adb_logo_<n>.c  LVGL 9 RGB565 image (no alpha)

Each logo's dark backdrop is keyed out and replaced with the app background
(UI_C_BG in ui_internal.h), so the logo blends into the splash screen.
Needs Pillow.
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
APP_BG = (0x14, 0x11, 0x0F)  # UI_C_BG
SIZE = 272                    # square logo, fits the 320 px wide screen
LABEL_BOX = (0, 0, 150, 60)   # "Option N" caption in each quadrant's top-left
KEY_LO, KEY_HI = 20, 44       # colour distance from backdrop: fully bg .. fully logo
MARGIN = 20                   # backdrop kept around the logo (source px)
FEATHER = 18                  # edge fade into the app background (source px)


def backdrop(q):
    """Median colour of the quadrant's border (the dark backdrop)."""
    w, h = q.size
    px = [q.getpixel((x, y)) for x in range(0, w, 4) for y in (h - 3, h - 10)]
    px += [q.getpixel((x, y)) for y in range(60, h, 4) for x in (2, w - 3)]
    return tuple(sorted(c[i] for c in px)[len(px) // 2] for i in range(3))


def dist(a, b):
    return max(abs(a[i] - b[i]) for i in range(3))


def logo_bbox(q, bg):
    w, h = q.size
    xs, ys = [], []
    for y in range(h):
        for x in range(w):
            if LABEL_BOX[0] <= x < LABEL_BOX[2] and LABEL_BOX[1] <= y < LABEL_BOX[3]:
                continue
            if dist(q.getpixel((x, y)), bg) > KEY_HI:
                xs.append(x)
                ys.append(y)
    return min(xs), min(ys), max(xs) + 1, max(ys) + 1


def key_to_app_bg(im, bg):
    """Replace the backdrop with APP_BG, and fade the square's edges so no
    seam shows where the logo meets the splash background."""
    out = im.copy()
    pix = out.load()
    for y in range(out.height):
        for x in range(out.width):
            p = pix[x, y]
            a = min(1.0, max(0.0, (dist(p, bg) - KEY_LO) / (KEY_HI - KEY_LO)))
            edge = min(x, y, out.width - 1 - x, out.height - 1 - y)
            a *= min(1.0, edge / FEATHER)
            pix[x, y] = tuple(round(APP_BG[i] * (1 - a) + p[i] * a) for i in range(3))
    return out


def to_lvgl_c(im, name):
    data = bytearray()
    raw = im.tobytes()
    for i in range(0, len(raw), 3):
        r, g, b = raw[i], raw[i + 1], raw[i + 2]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data += bytes((v & 0xFF, v >> 8))  # little endian, as LVGL expects
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    w, h = im.size
    return (
        f"/* Generated by tools/branding/make_logos.py. Do not edit. */\n"
        f'#include "lvgl.h"\n\n'
        f"static const uint8_t {name}_map[] = {{\n    " + ",\n    ".join(lines) + "\n};\n\n"
        f"const lv_image_dsc_t {name} = {{\n"
        f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565,\n"
        f"                .w = {w}, .h = {h}, .stride = {w * 2} }},\n"
        f"    .data_size = sizeof({name}_map),\n"
        f"    .data = {name}_map,\n"
        f"}};\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", default=ROOT / "assets/branding/logo_options.webp", type=Path)
    args = ap.parse_args()
    sheet = Image.open(args.sheet).convert("RGB")
    qw, qh = sheet.width // 2, sheet.height // 2
    for n in range(4):
        qx, qy = (n % 2) * qw, (n // 2) * qh
        q = sheet.crop((qx, qy, qx + qw, qy + qh))
        bg = backdrop(q)
        q.paste(bg, LABEL_BOX)  # drop the "Option N" caption
        x0, y0, x1, y1 = logo_bbox(q, bg)
        side = max(x1 - x0, y1 - y0) + 2 * MARGIN
        cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
        box = (cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side)
        logo = q.crop(box)  # out-of-range areas come back black; keyed to bg below
        logo = key_to_app_bg(logo, bg).resize((SIZE, SIZE), Image.LANCZOS)
        logo.save(ROOT / f"assets/branding/logo_{n + 1}.png")
        name = f"adb_logo_{n + 1}"
        (ROOT / f"firmware/components/ui/assets/{name}.c").write_text(to_lvgl_c(logo, name))
        print(f"{name}: backdrop {bg}, crop {box} -> {SIZE}x{SIZE}")


if __name__ == "__main__":
    main()
