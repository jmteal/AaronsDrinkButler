def write_json(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=1) + "\n")


def ingredients_json(ingredients: dict, recipes: list[dict]) -> dict:
    used: dict[str, int] = {}
    for r in recipes:
        for i in {x["ingredient_id"] for x in r["ingredients"]}:
            used[i] = used.get(i, 0) + 1
    rows = []
    for iid, ing in ingredients.items():
        if iid not in used:
            continue
        rows.append({
            "id": iid,
            "name": ing["name"],
            "category": ing["cat"],
            "substitutes": [s for s in ing["sub"] if s in used],
            "pantry_essential": bool(ing.get("essential", False)),
            "pantry_ignore": ing.get("pantry") is False,
            "abv": ing["abv"],
            "used_by": used[iid],
        })
    order = list(CATEGORY_LABELS)
    rows.sort(key=lambda r: (order.index(r["category"]), not r["pantry_essential"], r["name"].lower()))
    return {
        "schema_version": 1,
        "categories": [{"id": k, "label": v} for k, v in CATEGORY_LABELS.items()],
        "ingredients": rows,
    }


def attribution_md(recipes: list[dict]) -> str:
    photos = [r for r in recipes if r["image"]["kind"] == "photo"]
    lines = [
        "# Attribution",
        "",
        "This file is generated by `tools/data/build.py`. Do not edit by hand.",
        "",
        "## Recipe text and data",
        "",
        "- Recipe steps, notes and tags in `recipes.json` were written for this project and are "
        "licensed **CC BY 4.0** (https://creativecommons.org/licenses/by/4.0/).",
        "- Ingredient lists and amounts are facts. They were checked against these references "
        "(no text or images were copied from them):",
        "  - International Bartenders Association, official cocktail list and specs: https://iba-world.com/cocktails/all-cocktails/",
        "  - Wikipedia, *List of IBA official cocktails* and individual cocktail articles: https://en.wikipedia.org/",
        "  - Wikidata (CC0): https://www.wikidata.org/",
        "  - TheCocktailDB (development cross-check with the public test key; thank you!): https://www.thecocktaildb.com/",
        "- The glass icons in `icons/` are generated by our own code and are covered by the repository's licenses.",
        "",
        f"## Photos ({len(photos)})",
        "",
        "Each photo comes from Wikimedia Commons under the license shown. All were **cropped and resized** "
        "(to 320×240 and 96×96 JPEG) for this project; the resized copies keep the original license. "
        "CC BY-SA photos remain under CC BY-SA.",
        "",
        "| Drink | Photo (title) | Author | License | Source |",
        "|---|---|---|---|---|",
    ]
    for r in sorted(photos, key=lambda r: r["name"].lower()):
        im = r["image"]
        title = im["title"].replace("File:", "").replace("|", "\\|")
        author = (im["author"] or "Unknown").replace("|", "\\|")
        lic = f"[{im['license']}]({im['license_url']})" if im.get("license_url") else im["license"]
        lines.append(f"| {r['name']} | *{title}* | {author} | {lic} | {im['source_url']} — {im['modified']} |")
    lines.append("")
    return "\n".join(lines)


def fmt_amount(i: dict) -> str:
    a, u = i.get("amount"), i.get("unit")
    if u == "top":
        return "top: "
    if a is None:
        return f"{u}: " if u else ""
    return f"{a:g} {u} " if isinstance(a, float) else f"{a} {u} "


def review_csv(path: Path, recipes: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = ["id", "name", "reviewed", "flavor", "season", "occasion", "difficulty", "color_name",
            "color_hex", "base_spirit", "strength", "abv_est", "alcoholic", "glass", "method",
            "iba_category", "image_kind", "notes"]
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in recipes:
            t = r["tags"]
            w.writerow([
                r["id"], r["name"], "yes" if r["review"]["tags_reviewed"] else "",
                ",".join(t["flavor"]), ",".join(t["season"]), ",".join(t["occasion"]),
                t["difficulty"], r["color"]["name"], r["color"]["hex"], ",".join(t["base_spirit"]),
                t["strength"], r["abv_est"], t["alcoholic"], r["glass"], r["method"],
                t["iba_category"] or "", r["image"]["kind"], "",
            ])


